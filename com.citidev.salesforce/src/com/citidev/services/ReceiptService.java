    public int syncReceiptsFromSalesforce() {
        List<ReceiptDTO> dtos = getAllReceipts();

        if (dtos == null || dtos.isEmpty()) {
            log.warn("No receipts found in Salesforce.");
            return 0;
        }

        log.info("Starting Salesforce, ERP receipt sync...");

        Map<String, MPayment> existing = fetchExistingPayments(
                dtos.stream().map(ReceiptDTO::getId).collect(Collectors.toList())
        );

        int syncedCount = 0;

        for (ReceiptDTO dto : dtos) {
            MPayment payment = existing.get(dto.getId());

            if (payment == null) {
                payment = new MPayment(Env.getCtx(), 0, null);
            } else if (payment.isProcessed()) {
                log.warn("Skipping processed payment: " + dto.getName());
                continue;
            }

            populatePayment(payment, dto);
            try {
                payment.saveEx();
                syncedCount++;
            } catch (Exception e) {
                log.error("Failed to save payment for: " + dto.getName() + " | " + e.getMessage());
            }
        }

        log.info("Receipts synchronized successfully: " + syncedCount);
        return syncedCount;
    }
    
    public int syncReceiptsToSalesforce() {
        List<MPayment> payments = new Query(Env.getCtx(), MPayment.Table_Name, "SF_UID IS NULL AND IsActive='Y'", null)
                .list();

        if (payments == null || payments.isEmpty()) {
            log.info("No new payments found to sync to Salesforce.");
            return 0;
        }

        int syncedCount = 0;

        for (MPayment payment : payments) {
            try {
                // Convert MPayment to DTO
                ReceiptDTO dto = toReceiptDTO(payment);

                // Send to Salesforce
                ReceiptDTO response = receiptApi.createReceipt(dto);

                // Save returned SF ID
                if (response != null && response.getId() != null) {
                    payment.set_ValueOfColumn("SF_UID", response.getId());
                    payment.saveEx();
                    syncedCount++;
                    log.info("Synced Payment [" + payment.getDocumentNo() + "] with SF_UID: " + response.getId());
                }

            } catch (Exception e) {
                log.error("Failed to sync payment: " + payment.getDocumentNo() + " | " + e.getMessage());
            }
        }

        log.info("Payments synced to Salesforce: " + syncedCount);
        return syncedCount;
    }
    
